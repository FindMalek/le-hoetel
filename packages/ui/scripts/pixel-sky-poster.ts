import { writeFileSync } from "node:fs"
import { deflateSync } from "node:zlib"
import { createSky, POSTER_COLS, POSTER_ROWS } from "../src/brand/pixel-sky-grid"

// sRGB values of --sky-1..4 and --cloud in theme.css; a PNG cannot read CSS variables.
const PALETTE = ["#0a84ff", "#5aaeff", "#a9d4ff", "#dcefff", "#ffffff"]

const sky = createSky()

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
  return c >>> 0
})

function crc32(bytes: Uint8Array): number {
  let c = 0xffffffff
  for (const b of bytes) c = (CRC_TABLE[(c ^ b) & 0xff] ?? 0) ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}

function chunk(type: string, data: Uint8Array): Buffer {
  const body = Buffer.concat([Buffer.from(type, "ascii"), data])
  const out = Buffer.alloc(body.length + 8)
  out.writeUInt32BE(data.length, 0)
  body.copy(out, 4)
  out.writeUInt32BE(crc32(body), body.length + 4)
  return out
}

function indexedPng(cells: Uint8Array, cols: number, rows: number): Buffer {
  const header = Buffer.alloc(13)
  header.writeUInt32BE(cols, 0)
  header.writeUInt32BE(rows, 4)
  header.set([8, 3, 0, 0, 0], 8)
  const plte = Buffer.from(PALETTE.flatMap((hex) => [1, 3, 5].map((i) => Number.parseInt(hex.slice(i, i + 2), 16))))
  const raw = Buffer.alloc((cols + 1) * rows)
  for (let y = 0; y < rows; y++) raw.set(cells.subarray(y * cols, (y + 1) * cols), y * (cols + 1) + 1)
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", header),
    chunk("PLTE", plte),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", new Uint8Array()),
  ])
}

function dataUrl(clearCenter: boolean): string {
  const png = indexedPng(sky({ cols: POSTER_COLS, rows: POSTER_ROWS, clearCenter }), POSTER_COLS, POSTER_ROWS)
  console.log(`poster clearCenter=${clearCenter}: ${png.length} bytes`)
  return `data:image/png;base64,${png.toString("base64")}`
}

const target = new URL("../src/brand/pixel-sky-poster.ts", import.meta.url)
writeFileSync(
  target,
  `// Generated by \`pnpm -F @ritorno/ui sky:poster\` from pixel-sky-grid.ts. Do not edit.\nexport const SKY_POSTER = "${dataUrl(false)}"\nexport const SKY_POSTER_CLEAR = "${dataUrl(true)}"\n`,
)
